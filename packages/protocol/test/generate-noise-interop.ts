/**
 * Regenerate test/interop/noise-crh.json: the Noise handshake as crh uses it, with the prologue
 * NOISE_PROLOGUE_PREFIX || challenge. The transcript is produced by the TypeScript implementation
 * in packages/noise; client/internal/noise and packages/noise reproduce it byte for byte.
 *   node test/generate-noise-interop.ts
 */
import { writeFileSync } from "node:fs";
import { HandshakeState, keyPairFromPrivate } from "../../noise/src/index.ts";
import { NOISE_PROLOGUE_PREFIX } from "../src/messages.ts";

const bytes = (text: string): Uint8Array => new TextEncoder().encode(text);
const hex = (value: Uint8Array): string => Buffer.from(value).toString("hex");
const repeat = (byte: string): string => byte.repeat(32);

const clientStatic = repeat("01");
const serverStatic = repeat("02");
const clientEphemeral = repeat("03");
const serverEphemeral = repeat("04");
const challenge = Buffer.from(repeat("05"), "hex");
const initPayload = bytes("init payload");
const responsePayload = bytes("response payload");
const clientToServer = bytes("client says hi");
const serverToClient = bytes("server says hi");

const prologue = Buffer.concat([Buffer.from(NOISE_PROLOGUE_PREFIX), challenge]);
const server = keyPairFromPrivate(Buffer.from(serverStatic, "hex"));
const initiator = HandshakeState.initiator({
	prologue,
	staticKey: keyPairFromPrivate(Buffer.from(clientStatic, "hex")),
	remoteStaticKey: server.publicKey,
	ephemeralKey: keyPairFromPrivate(Buffer.from(clientEphemeral, "hex")),
});
const responder = HandshakeState.responder({
	prologue,
	staticKey: server,
	ephemeralKey: keyPairFromPrivate(Buffer.from(serverEphemeral, "hex")),
});

const message1 = initiator.writeMessage(initPayload);
responder.readMessage(message1);
const message2 = responder.writeMessage(responsePayload);
initiator.readMessage(message2);
const clientCiphers = initiator.split();
const serverCiphers = responder.split();
const empty = new Uint8Array(0);

const fixture = {
	comment: `Noise handshake as used by crh (prologue "${NOISE_PROLOGUE_PREFIX}" || challenge). Generated by packages/protocol/test/generate-noise-interop.ts; verified by client/internal/noise and packages/noise tests.`,
	client_static: clientStatic,
	server_static: serverStatic,
	client_ephemeral: clientEphemeral,
	server_ephemeral: serverEphemeral,
	challenge: challenge.toString("hex"),
	init_payload: hex(initPayload),
	response_payload: hex(responsePayload),
	client_to_server: hex(clientToServer),
	server_to_client: hex(serverToClient),
	message1: hex(message1),
	message2: hex(message2),
	transport_c2s: hex(clientCiphers.send.encrypt(empty, clientToServer)),
	transport_s2c: hex(serverCiphers.send.encrypt(empty, serverToClient)),
	handshake_hash: hex(clientCiphers.handshakeHash),
};

const target = new URL("../../../test/interop/noise-crh.json", import.meta.url);
writeFileSync(target, `${JSON.stringify(fixture, null, "\t")}\n`);
console.log(`wrote ${target.pathname}`);
